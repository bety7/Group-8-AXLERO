"use client";

import { useState } from "react";
import { pickViz } from "@/lib/chartSpec";
import { cellText } from "@/lib/format";
import type { Part } from "@/lib/types";
import Chart from "./Chart";

type ToolPart = Extract<Part, { type: "tool" }>;
type Tab = "visual" | "table" | "sql" | "api";

function summarize(part: ToolPart): string {
  const a = part.args ?? {};
  const strip = (s: string) => s.split(".").pop()?.replace(/_/g, " ") ?? s;
  const what = (a.measures ?? []).map(strip).join(", ") || "query";
  const by = (a.dimensions ?? []).map(strip);
  if (a.granularity) by.unshift(a.granularity);
  const range = Array.isArray(a.date_range) ? a.date_range.join(" to ") : a.date_range;
  return `${what}${by.length ? ` by ${by.join(", ")}` : ""}${range ? ` | ${range}` : ""}`;
}

function Code({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);
  return (
    <div className="relative">
      <button
        onClick={() => { navigator.clipboard.writeText(text); setCopied(true); setTimeout(() => setCopied(false), 1500); }}
        className="absolute right-2 top-2 rounded border border-line bg-card px-2 py-0.5 text-xs text-mute hover:text-ink"
      >
        {copied ? "Copied" : "Copy"}
      </button>
      <pre className="max-h-72 overflow-auto rounded bg-ink p-4 pr-16 font-mono text-[12.5px] leading-relaxed text-[#e6ebf5]">{text}</pre>
    </div>
  );
}

export default function ResultCard({ part }: { part: ToolPart }) {
  const result = part.result;
  const columns = result?.columns ?? [];
  const rows = result?.rows ?? [];
  const viz = result?.ok ? pickViz(columns, rows) : "table";
  const [tab, setTab] = useState<Tab>("visual");
  const active: Tab = tab === "visual" && viz === "table" ? "table" : tab;

  const tabs: { id: Tab; label: string }[] = [
    ...(viz !== "table" ? [{ id: "visual" as Tab, label: viz === "kpi" ? "Result" : "Chart" }] : []),
    { id: "table", label: "Table" },
    { id: "sql", label: "View SQL" },
    { id: "api", label: "View API call" },
  ];

  const apiCall = result?.query ? `POST /cubejs-api/v1/load\n\n${JSON.stringify({ query: result.query }, null, 2)}` : "";
  const sqlText = result?.sql ? `${result.sql}\n\n-- params: ${JSON.stringify(result.params ?? [])}` : "-- SQL is generated by the semantic layer; not available for this query.";

  return (
    <section className="my-4 overflow-hidden rounded-md border border-line border-l-4 border-l-accent bg-card" aria-label="Semantic layer query">
      <header className="flex items-center justify-between gap-3 border-b border-line px-4 py-2.5">
        <p className="truncate text-sm font-medium">{summarize(part)}</p>
        <span className="shrink-0 text-xs text-mute">
          {part.status === "running" ? "Querying semantic layer..." : result?.ok ? `${result.row_count} rows, ${result.elapsed_ms} ms` : "Blocked"}
        </span>
      </header>

      {part.status === "running" && <div className="thinking px-4 py-6"><span /><span /><span /></div>}

      {result && !result.ok && (
        <div className="px-4 py-4 text-sm">
          <p className="font-medium text-flag">Query rejected by governance</p>
          <p className="mt-1 text-mute">{result.error}</p>
          <p className="mt-1 text-mute">The agent will adjust the query and try again.</p>
        </div>
      )}

      {result?.ok && (
        <>
          <nav className="flex gap-1 border-b border-line px-2 pt-1.5" role="tablist">
            {tabs.map((t) => (
              <button
                key={t.id} role="tab" aria-selected={active === t.id} onClick={() => setTab(t.id)}
                className={`rounded-t px-3 py-1.5 text-sm ${active === t.id ? "border-b-2 border-accent font-medium text-ink" : "text-mute hover:text-ink"}`}
              >
                {t.label}
              </button>
            ))}
          </nav>

          <div className="p-4">
            {active === "visual" && viz === "kpi" && (
              <div className="flex flex-wrap gap-x-10 gap-y-4">
                {columns.filter((c) => c.kind === "measure").map((c) => (
                  <div key={c.key}>
                    <p className="text-sm text-mute">{c.label}</p>
                    <p className="num font-display text-4xl font-semibold tracking-tight">{cellText(rows[0], c, true)}</p>
                  </div>
                ))}
              </div>
            )}
            {active === "visual" && (viz === "line" || viz === "bar") && <Chart columns={columns} rows={rows} viz={viz} />}

            {active === "table" && (
              <div className="max-h-72 overflow-auto">
                <table className="w-full border-collapse text-sm">
                  <thead>
                    <tr>{columns.map((c) => (
                      <th key={c.key} className={`sticky top-0 border-b border-line bg-card px-3 py-2 font-medium text-mute ${c.kind === "measure" ? "text-right" : "text-left"}`}>{c.label}</th>
                    ))}</tr>
                  </thead>
                  <tbody>
                    {rows.map((r, i) => (
                      <tr key={i} className="border-b border-line/60 last:border-0">
                        {columns.map((c) => (
                          <td key={c.key} className={`px-3 py-1.5 ${c.kind === "measure" ? "num text-right" : ""}`}>{cellText(r, c)}</td>
                        ))}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}

            {active === "sql" && <Code text={sqlText} />}
            {active === "api" && <Code text={apiCall} />}
          </div>

          {!!result.notes?.length && (
            <footer className="border-t border-line px-4 py-2 text-xs text-mute">
              Guardrails applied: {result.notes.join(" ")}
            </footer>
          )}
        </>
      )}
    </section>
  );
}
